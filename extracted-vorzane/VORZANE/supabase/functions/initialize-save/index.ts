import { createClient } from "npm:@supabase/supabase-js@2";
import { createFreshState, normalizeGameState } from "../../../src/game/model.ts";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type",
  "Access-Control-Allow-Methods": "POST, OPTIONS",
};

function json(body: unknown, status = 200): Response {
  return new Response(JSON.stringify(body), {
    status,
    headers: { ...corsHeaders, "Content-Type": "application/json" },
  });
}

export function createInitializeSaveHandler(
  makeClient: typeof createClient = createClient,
  getEnv: (name: string) => string | undefined = (name) => Deno.env.get(name),
) {
  return async (request: Request): Promise<Response> => {
    if (request.method === "OPTIONS") return new Response(null, { headers: corsHeaders });
    if (request.method !== "POST") return json({ error: "Method not allowed" }, 405);

    const authHeader = request.headers.get("Authorization") ?? "";
    if (!authHeader.startsWith("Bearer ")) return json({ error: "Unauthorized" }, 401);

    const url = getEnv("SUPABASE_URL");
    const anonKey = getEnv("SUPABASE_ANON_KEY");
    const serviceRoleKey = getEnv("SUPABASE_SERVICE_ROLE_KEY");
    if (!url || !anonKey || !serviceRoleKey) return json({ error: "Server configuration is incomplete" }, 500);

    // The client cannot submit a save snapshot. Initialization always uses the
    // canonical fresh state generated by this server function.
    try {
      const payload = await request.json();
      if (!payload || typeof payload !== "object" || Array.isArray(payload) || Object.keys(payload).length !== 0) {
        return json({ error: "Initialization accepts an empty payload only" }, 400);
      }
    } catch {
      return json({ error: "Invalid JSON body" }, 400);
    }

    const caller = makeClient(url, anonKey, {
      global: { headers: { Authorization: authHeader } },
      auth: { persistSession: false, autoRefreshToken: false },
    });
    const { data: userData, error: userError } = await caller.auth.getUser();
    if (userError || !userData.user) return json({ error: "Unauthorized" }, 401);

    const userId = userData.user.id;
    const { data: existing, error: readError } = await caller
      .from("player_saves")
      .select("game_state, updated_at")
      .eq("user_id", userId)
      .maybeSingle();

    if (readError) return json({ error: "Could not load save" }, 500);
    if (existing) {
      const state = normalizeGameState(existing.game_state);
      if (!state) return json({ error: "Player state is invalid" }, 409);
      return json({ state, updatedAt: existing.updated_at, created: false });
    }

    const admin = makeClient(url, serviceRoleKey, {
      auth: { persistSession: false, autoRefreshToken: false },
    });
    // Every newly registered account gets a fresh server-issued epoch. This
    // retires any legacy/device-wide cache left by accounts deleted at relaunch.
    const freshState = {
      ...createFreshState(),
      serverResetEpoch: crypto.randomUUID(),
    };
    const { data: inserted, error: insertError } = await admin
      .from("player_saves")
      .upsert(
        { user_id: userId, game_state: freshState },
        { onConflict: "user_id", ignoreDuplicates: true },
      )
      .select("user_id")
      .maybeSingle();

    if (insertError) return json({ error: "Could not initialize save" }, 500);

    // Re-read through the caller JWT so the returned row still obeys owner RLS.
    const { data: created, error: verifyError } = await caller
      .from("player_saves")
      .select("game_state, updated_at")
      .eq("user_id", userId)
      .maybeSingle();

    if (verifyError) return json({ error: "Could not verify initialized save" }, 500);
    if (!created) return json({ error: "Initialized save is not visible to its owner" }, 500);
    const state = normalizeGameState(created.game_state);
    if (!state) return json({ error: "Initialized player state is invalid" }, 409);

    return json({ state, updatedAt: created.updated_at, created: !!inserted });
  };
}

if (import.meta.main) {
  Deno.serve(createInitializeSaveHandler());
}
